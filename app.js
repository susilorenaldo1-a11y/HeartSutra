const STORAGE_KEY = 'heart_sutra_data';

let state = {
  currentSession: 0,
  cumulativeTotal: 0,
  logs: [],
  lang: 'zh'
};

function loadState() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      state.cumulativeTotal = parsed.cumulativeTotal ?? 0;
      state.currentSession = parsed.currentSession ?? 0;
      state.logs = parsed.logs ?? [];
    }
  } catch (e) {
    console.warn('Failed to load state', e);
  }
}

function saveState() {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({
      cumulativeTotal: state.cumulativeTotal,
      currentSession: state.currentSession,
      logs: state.logs
    }));
  } catch (e) {
    console.warn('Failed to save state', e);
  }
}

function renderCounter() {
  document.getElementById('tapCount').textContent = state.currentSession;
  document.getElementById('cumulativeTotal').textContent = state.cumulativeTotal;
}

function renderSutra() {
  const data = SUTRA[state.lang];
  document.getElementById('sutraTitle').textContent = data.title;
  const body = document.getElementById('sutraBody');
  body.dataset.lang = state.lang;
  body.innerHTML = data.lines.map((l) => `<div class="line">${escapeHtml(l)}</div>`).join('');

  document.querySelectorAll('.tab').forEach((tab) => {
    tab.classList.toggle('active', tab.dataset.lang === state.lang);
  });
}

function renderLog() {
  const list = document.getElementById('logList');
  if (state.logs.length === 0) {
    list.innerHTML = '<div class="log-empty">No sessions logged yet.</div>';
    return;
  }
  list.innerHTML = state.logs.map((log, i) => {
    const note = log.note ? `<div class="log-note">${escapeHtml(log.note)}</div>` : '';
    return `
      <div class="log-entry">
        <div class="log-top">
          <span class="log-count">${log.count}</span>
          <span class="log-date">${formatDate(log.date)}</span>
          <button class="log-del" data-index="${i}" title="Delete">🗑</button>
        </div>
        ${note}
      </div>`;
  }).join('');

  list.querySelectorAll('.log-del').forEach((btn) => {
    btn.addEventListener('click', () => {
      const idx = parseInt(btn.dataset.index, 10);
      state.cumulativeTotal -= state.logs[idx].count;
      state.logs.splice(idx, 1);
      saveState();
      renderCounter();
      renderLog();
    });
  });
}

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}

function formatDate(ts) {
  const d = new Date(ts);
  return d.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' }) +
    ' ' + d.toLocaleTimeString(undefined, { hour: '2-digit', minute: '2-digit' });
}

function openModal(id) {
  document.getElementById(id).classList.add('open');
}

function closeModal(id) {
  document.getElementById(id).classList.remove('open');
}

function init() {
  loadState();
  renderCounter();
  renderSutra();

  document.getElementById('tapBtn').addEventListener('click', () => {
    state.currentSession += 1;
    saveState();
    renderCounter();
  });

  document.getElementById('undoBtn').addEventListener('click', () => {
    if (state.currentSession > 0) {
      state.currentSession -= 1;
      saveState();
      renderCounter();
    }
  });

  document.getElementById('resetSessionBtn').addEventListener('click', () => {
    state.currentSession = 0;
    saveState();
    renderCounter();
  });

  document.querySelectorAll('.tab').forEach((tab) => {
    tab.addEventListener('click', () => {
      state.lang = tab.dataset.lang;
      renderSutra();
    });
  });

  document.getElementById('saveSessionBtn').addEventListener('click', () => {
    if (state.currentSession === 0) return;
    document.getElementById('saveCount').textContent = state.currentSession;
    document.getElementById('noteInput').value = '';
    openModal('saveModal');
  });

  document.getElementById('confirmSaveBtn').addEventListener('click', () => {
    const note = document.getElementById('noteInput').value.trim();
    state.logs.push({
      count: state.currentSession,
      note: note || null,
      date: Date.now()
    });
    state.cumulativeTotal += state.currentSession;
    state.currentSession = 0;
    saveState();
    renderCounter();
    closeModal('saveModal');
  });

  document.getElementById('cancelSaveBtn').addEventListener('click', () => closeModal('saveModal'));
  document.getElementById('closeSaveBtn').addEventListener('click', () => closeModal('saveModal'));

  document.getElementById('viewLogBtn').addEventListener('click', () => {
    renderLog();
    openModal('logModal');
  });

  document.getElementById('closeLogBtn').addEventListener('click', () => closeModal('logModal'));
  document.getElementById('closeLogBtn2').addEventListener('click', () => closeModal('logModal'));

  document.getElementById('clearLogBtn').addEventListener('click', () => {
    state.logs = [];
    state.cumulativeTotal = 0;
    saveState();
    renderCounter();
    renderLog();
  });

  // Close modal on backdrop click
  document.querySelectorAll('.modal').forEach((modal) => {
    modal.addEventListener('click', (e) => {
      if (e.target === modal) closeModal(modal.id);
    });
  });
}

document.addEventListener('DOMContentLoaded', init);
